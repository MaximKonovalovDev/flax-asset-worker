def shared_pack_ids(*, wave: int | None = None, include_legacy: bool = True) -> tuple[str, ...]:
    families = SHARED_PACK_FAMILIES
    if wave is not None:
        families = tuple(family for family in families if family.wave == wave)
    elif not include_legacy:
        families = tuple(family for family in families if family.wave > 0)
    return tuple(family.pack_id for family in families)


def get_shared_pack_family(pack_id: str) -> SharedPackFamily:
    for family in SHARED_PACK_FAMILIES:
        if family.pack_id == pack_id:
            return family
    raise KeyError(pack_id)


def planned_shared_pack_families(*, wave: int | None = None) -> tuple[SharedPackFamily, ...]:
    if wave is None:
        return tuple(family for family in SHARED_PACK_FAMILIES if family.wave > 0)
    return tuple(family for family in SHARED_PACK_FAMILIES if family.wave == wave)


def shared_pack_targets(game_scope: str = "shared") -> dict[str, Path]:
    return {
        family.pack_id: publish_payload_dir(game_scope=game_scope, pack_id=family.pack_id)
        for family in SHARED_PACK_FAMILIES
    }
