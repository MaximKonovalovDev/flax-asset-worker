@dataclass(frozen=True)
class SharedPackFamily:
    pack_id: str
    domain: str
    description: str
    preferred_lanes: tuple[str, ...]
    seed_strategy: str
    reuse_targets: tuple[str, ...]
    asset_category: str = ""
    wave: int = 0
    primary_bridge_id: str = ""
    fallback_bridge_ids: tuple[str, ...] = ()
    request_count: int = 3
    search_terms: tuple[str, ...] = ()
    review_slice: str = ""

    def to_dict(self) -> dict[str, object]:
        payload: dict[str, object] = {
            "pack_id": self.pack_id,
            "domain": self.domain,
            "description": self.description,
            "preferred_lanes": list(self.preferred_lanes),
            "seed_strategy": self.seed_strategy,
            "reuse_targets": list(self.reuse_targets),
        }
        if self.asset_category:
            payload["asset_category"] = self.asset_category
        if self.wave:
            payload["wave"] = self.wave
        if self.primary_bridge_id:
            payload["primary_bridge_id"] = self.primary_bridge_id
        if self.fallback_bridge_ids:
            payload["fallback_bridge_ids"] = list(self.fallback_bridge_ids)
        if self.request_count:
            payload["request_count"] = self.request_count
        if self.search_terms:
            payload["search_terms"] = list(self.search_terms)
        if self.review_slice:
            payload["review_slice"] = self.review_slice
        return payload


def _family(
    *,
    pack_id: str,
    domain: str,
    description: str,
    preferred_lanes: tuple[str, ...],
    seed_strategy: str,
    reuse_targets: tuple[str, ...],
    asset_category: str = "",
    wave: int = 0,
    primary_bridge_id: str = "",
    fallback_bridge_ids: tuple[str, ...] = (),
    request_count: int = 3,
    search_terms: tuple[str, ...] = (),
    review_slice: str = "",
) -> SharedPackFamily:
    return SharedPackFamily(
        pack_id=pack_id,
        domain=domain,
        description=description,
        preferred_lanes=preferred_lanes,
        seed_strategy=seed_strategy,
        reuse_targets=reuse_targets,
        asset_category=asset_category,
        wave=wave,
        primary_bridge_id=primary_bridge_id,
        fallback_bridge_ids=fallback_bridge_ids,
        request_count=request_count,
        search_terms=search_terms,
        review_slice=review_slice,
    )


